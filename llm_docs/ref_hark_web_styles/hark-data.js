  checklistsForLocation: function (locId) {
    var out = [];
    for (var id in this.checklists) {
      if (this.checklists[id].locationId === locId) out.push(Object.assign({ id: id }, this.checklists[id]));
    }
    out.sort(function (a, b) { return b.date.localeCompare(a.date) || b.time.localeCompare(a.time); });
    return out;
  },
  speciesTotalsForLocation: function (locId) {
    var map = {};
    this.checklistsForLocation(locId).forEach(function (cl) {
      cl.species.forEach(function (sp) {
        if (!map[sp.common]) map[sp.common] = { common: sp.common, sci: sp.sci, total: 0, onlyX: true };
        if (typeof sp.count === 'number') { map[sp.common].total += sp.count; map[sp.common].onlyX = false; }
      });
    });
    return Object.keys(map).map(function (k) { return map[k]; }).sort(function (a, b) {
      if (a.onlyX && !b.onlyX) return 1;
      if (!a.onlyX && b.onlyX) return -1;
      if (!a.onlyX && !b.onlyX) return b.total - a.total;
      return a.common.localeCompare(b.common);
    });
  },
  countForLocation: function (locId) {
    var total = 0;
    this.checklistsForLocation(locId).forEach(function (cl) { total += cl.species.length; });
    return total;
  },
  allMediaGroups: function () {
    var out = [];
    for (var id in this.checklists) {
      if (this.checklists[id].media) out.push(Object.assign({ id: id }, this.checklists[id]));
    }
    out.sort(function (a, b) { return b.date.localeCompare(a.date) || b.time.localeCompare(a.time); });
    return out;
  },
  latestChecklistDate: function () {
    var dates = [];
    for (var id in this.checklists) dates.push(this.checklists[id].date);
    dates.sort().reverse();
    if (!dates[0]) return '';
    var d = new Date(dates[0] + 'T00:00:00');
    return d.toLocaleDateString('en-US', { day: 'numeric', month: 'short', year: 'numeric' });
  },
  lifeListSize: function () {
    var set = {};
    for (var id in this.checklists) this.checklists[id].species.forEach(function (sp) { set[sp.common] = true; });
    return Object.keys(set).length;
  }
